#!/usr/bin/env python3
"""Render complete reading indexes and task-specific recommendation histories.

Paper files stay in their original branch. A historical role is local to one task;
it never removes a paper from either the complete library or another task.
"""

from __future__ import annotations

import argparse
import hashlib
import html
import json
import os
from pathlib import Path
import sys

if __package__:
    from .task_lifecycle import validate_task_frontiers
    from .library_review import DECISION_LABELS, validate_library_review
else:
    from task_lifecycle import validate_task_frontiers
    from library_review import DECISION_LABELS, validate_library_review


BRANCH_DIRECTORIES = {
    "A": "A_executable_world_representation",
    "B": "B_interactive_generation_pcg",
    "C": "C_spatial_intelligence",
    "D": "D_vla_world_action_models",
    "E": "E_evaluation_data_infrastructure",
}
ROLE_LABELS = {
    "current": "当前主推荐",
    "alternative": "并列备选",
    "historical": "历史基线",
    "unreviewed": "未审查",
}
GENERATED = "<!-- Generated by scripts/render_reading_indexes.py; edit the source JSON instead. -->"


def reading_status(paper: dict, roles: list[str]) -> str | None:
    """Admission quality and today's task recommendation are separate judgments."""
    decision = paper.get("curation_status")
    if decision is None and paper.get("acceptance_policy_version") == 2:
        decision = "priority"
    if decision == "priority" and "current" not in roles:
        return "reference"
    return decision


def markdown(value: object) -> str:
    """Keep labels/text from accidentally becoming Markdown syntax."""
    return str(value).replace("\\", "\\\\").replace("[", "\\[").replace("]", "\\]").replace("\n", " ")


def paper_anchor(task_id: str, paper_url: str) -> str:
    digest = hashlib.sha256(paper_url.encode()).hexdigest()[:12]
    return f"task-{task_id}-paper-{digest}"


def relative_link(source: Path, target: Path) -> str:
    return Path(os.path.relpath(target, source.parent)).as_posix()


def paper_link(paper: dict, source: Path, root: Path) -> str:
    destination = relative_link(source, root / paper["deep_dive_path"])
    return f"[{markdown(paper['title'])}]({destination})"


def paper_sort_key(member: dict, papers: dict[str, dict]) -> tuple:
    paper = papers[member["paper_url"]]
    return (-paper["year"], paper["title"].casefold(), member["paper_url"])


def source_lines(member: dict) -> list[str]:
    evidence = member.get("evidence", [])
    if not evidence:
        return ["- 证据：尚未完成任务级比较审核。"]
    return [
        "- 证据："
        + f"[官方/原始来源]({item['source_url']}) — {markdown(item['locator'])}；"
        + f"{markdown(item['claim'])}（{markdown(item['source_quality'])} / {markdown(item['status'])}）。"
        for item in evidence
    ]


def member_lines(task: dict, member: dict, papers: dict[str, dict], source: Path, root: Path) -> list[str]:
    paper = papers[member["paper_url"]]
    lines = [
        f'<a id="{paper_anchor(task["task_id"], member["paper_url"])}"></a>',
        "",
        f"- 论文：{paper_link(paper, source, root)}（{paper['year']}）",
        f"- 任务角色：{ROLE_LABELS[member['role']]}",
    ]
    if member.get("reviewed_on"):
        lines.append(f"- 审核日期：{member['reviewed_on']}")
    status = reading_status(paper, [member["role"]])
    if status in DECISION_LABELS:
        anchor = "paper-" + hashlib.sha256(member["paper_url"].encode()).hexdigest()[:12]
        lines.append(f"- 阅读位置：[{DECISION_LABELS[status]}](library_review.md#{anchor})")
    if member["role"] == "historical":
        successor_url = member["superseded_by"]
        successor = papers[successor_url]
        lines.extend([
            f"- 后继：[{markdown(successor['title'])}](#{paper_anchor(task['task_id'], successor_url)})",
            f"- 归档原因：{markdown(member['reason'])}",
            f"- 实质改进：{markdown(member['comparison']['improvements'])}",
            f"- 取舍与适用边界：{markdown(member['comparison']['tradeoffs'])}",
            f"- 保留价值：{markdown(member['comparison']['retained_value'])}",
        ])
    else:
        lines.append(f"- 判断依据：{markdown(member['reason'])}")
    lines.extend(source_lines(member))
    return lines


def historical_tree(task: dict, parent_url: str, children: dict[str, list[dict]], papers: dict[str, dict], source: Path, root: Path) -> list[str]:
    lines: list[str] = []
    for member in sorted(children.get(parent_url, []), key=lambda item: paper_sort_key(item, papers)):
        paper = papers[member["paper_url"]]
        lines.extend([
            "<details>",
            f"<summary>历史基线：{html.escape(paper['title'])}（{paper['year']}）</summary>",
            "",
        ])
        lines.extend(member_lines(task, member, papers, source, root))
        lines.append("")
        lines.extend(historical_tree(task, member["paper_url"], children, papers, source, root))
        lines.extend(["</details>", ""])
    return lines


def task_page(registry: dict, frontiers: dict, papers: dict[str, dict], root: Path, review: dict | None = None) -> str:
    source = root / "paper_reads/task_frontiers.md"
    tasks = sorted(frontiers["tasks"], key=lambda task: (not any(m["role"] == "current" for m in task["members"]) if review is not None else False, task["task_id"]))
    mapped_urls = {member["paper_url"] for task in tasks for member in task["members"]}
    reviewed = sum(any(member["role"] != "unreviewed" for member in task["members"]) for task in tasks)
    role_counts = {role: sum(member["role"] == role for task in tasks for member in task["members"]) for role in ROLE_LABELS}
    lines = [
        "# Task Frontiers / 任务级推荐与历史基线",
        "",
        GENERATED,
        "",
        f"任务数：{len(tasks)}；已有比较审核的任务：{reviewed}；完整精读库：{len(papers)} 篇。",
        "",
        "任务角色记录：" + "；".join(f"{ROLE_LABELS[role]} {role_counts[role]}" for role in ROLE_LABELS) + "。",
        f"尚未分配到任务：{len(set(papers) - mapped_urls)} 篇（未审查）。角色记录可包含同篇论文在不同任务中的不同判断。",
        "",
        "[返回完整精读库](README.md)",
        "",
        "推荐与归档只针对明确的 task 和评测范围。同一论文可在一个任务中作为历史基线，在另一个任务中仍为当前主推荐。",
        "尚未完成可比任务判断不等于已过时，也不默认成为当前主推荐。所有论文和精读原路径均保留。",
        "",
    ]
    if review is not None:
        lines.extend([f"全库已在 {review['review_date']} 完成来源/任务/准入复审；任务角色仍待定的条目，可在[逐篇复审](library_review.md)查看观察、视觉待定或来源问题。", ""])
    if tasks:
        lines.extend(["## 任务导航", ""])
        visible = [task for task in tasks if any(m["role"] == "current" for m in task["members"])] if review is not None else tasks
        others = [task for task in tasks if task not in visible]
        for task in visible:
            lines.append(f"- [{markdown(task['title'])}](#task-{task['task_id']})（{task['branch']}）")
        lines.append("")
        if others:
            lines.extend(["<details>", f"<summary>其他参考与待补证任务（{len(others)} 项）</summary>", ""])
            lines.extend(f"- [{markdown(task['title'])}](#task-{task['task_id']})（{task['branch']}）" for task in others)
            lines.extend(["", "</details>", ""])
    for task in tasks:
        pending_only = review is not None and not any(m["role"] == "current" for m in task["members"])
        if pending_only:
            lines.extend(["<details>", f"<summary>待补证任务：{html.escape(task['title'])}（{len(task['members'])} 篇）</summary>", ""])
        lines.extend([
            f'<a id="task-{task["task_id"]}"></a>',
            "",
            f"## {markdown(task['title'])}",
            "",
            f"Branch: {task['branch']} · task_id: `{task['task_id']}`",
            "",
            f"- 输入：{markdown(task['scope']['input'])}",
            f"- 输出：{markdown(task['scope']['output'])}",
            f"- 场景：{markdown(task['scope']['setting'])}",
            f"- 评测范围：{markdown(task['scope']['protocol'])}",
            "",
            "### 当前主推荐",
            "",
        ])
        members = sorted(task["members"], key=lambda member: paper_sort_key(member, papers))
        children: dict[str, list[dict]] = {}
        for member in members:
            if member["role"] == "historical":
                children.setdefault(member["superseded_by"], []).append(member)
        current = [member for member in members if member["role"] == "current"]
        if not current:
            lines.extend(["尚无经过比较审核的当前主推荐。", ""])
        for member in current:
            lines.extend([f"#### {markdown(papers[member['paper_url']]['title'])}", ""])
            lines.extend(member_lines(task, member, papers, source, root))
            lines.append("")
            lines.extend(historical_tree(task, member["paper_url"], children, papers, source, root))
        for role, heading in (("alternative", "并列备选"), ("unreviewed", "未审查成员")):
            group = [member for member in members if member["role"] == role]
            if review is not None and group:
                heading = "任务推荐待定" if role == "unreviewed" else heading
                lines.extend(["<details>", f"<summary>{heading}（{len(group)} 篇）</summary>", ""])
            else:
                lines.extend([f"### {heading}", ""])
            if not group:
                lines.extend(["暂无。", ""])
            for member in group:
                lines.extend([f"#### {markdown(papers[member['paper_url']]['title'])}", ""])
                lines.extend(member_lines(task, member, papers, source, root))
                lines.append("")
            if review is not None and group:
                lines.extend(["</details>", ""])
        if pending_only:
            lines.extend(["</details>", ""])
    unassigned = set(papers) - mapped_urls
    lines.extend([
        "## 尚未进入任务比较的存量论文",
        "",
        "<details>",
        f"<summary>展开未审查存量论文（共 {len(unassigned)} 篇）</summary>",
        "",
        "下列条目仍完整保留，任务角色为未审查。",
        "",
    ])
    for branch in sorted(registry["branches"], key=lambda branch: branch["id"]):
        group = [paper for paper in branch["papers"] if paper["url"] in unassigned]
        if not group:
            continue
        lines.extend([f"### {branch['id']}. {markdown(branch['name'])}", ""])
        lines.extend(f"- {paper_link(paper, source, root)}（未审查）" for paper in group)
        lines.append("")
    lines.extend(["</details>", ""])
    return "\n".join(lines).rstrip() + "\n"


def library_review_page(registry: dict, review: dict, root: Path) -> str:
    source = root / "paper_reads/library_review.md"
    papers = {p["url"]: p for b in registry["branches"] for p in b["papers"]}
    rows = review["reviews"]
    counts = {decision: sum(r["decision"] == decision for r in rows) for decision in DECISION_LABELS}
    reviewed_urls = {row["paper_url"] for row in rows}
    later = [paper for ref, paper in papers.items() if ref not in reviewed_urls]
    lines = ["# 存量论文复审与精选阅读", "", GENERATED, "",
             f"复审日期：{review['review_date']}。本次复审覆盖 {len(rows)} 篇；当前完整记录 {len(papers)} 篇。", "",
             "[按任务阅读](task_frontiers.md) · [全部保留记录](README.md)", "",
             "| 本轮结论 | 数量 |", "|---|---:|"]
    lines += [f"| {label} | {counts[decision]} |" for decision, label in DECISION_LABELS.items()]
    lines += ["", "优先阅读需重新满足三项四分门槛及适用证据要求。参考备选保留基础/独立价值，不表示重新通过新版核心准入。待补证不是论文质量差的结论；来源待修复记录应先纠错再引用。", "",
              "原始准入记录及旧精读保留供追溯，当前阅读位置以本页和分支复审为准。没有独立复现，不凭年龄或榜单分数制造全面替代关系。", ""]
    audits = {}
    for decision, label in DECISION_LABELS.items():
        group = [r for r in rows if r["decision"] == decision]
        if decision == "priority":
            lines.extend([f"## {label}（{len(group)} 篇）", ""])
        else:
            lines.extend(["<details>", f"<summary>{label}（{len(group)} 篇）</summary>", ""])
        for row in group:
            paper = papers[row["paper_url"]]
            artifact = row["review_artifact"]
            if artifact not in audits:
                doc = json.loads((root / artifact).read_text())
                audits[artifact] = {r["paper_url"]: r for r in doc["reviews"]}
            audit = audits[artifact][row["paper_url"]]
            anchor = "paper-" + hashlib.sha256(row["paper_url"].encode()).hexdigest()[:12]
            scores = " / ".join(str(row.get(key)) if row.get(key) is not None else "未定" for key in ("impact_score", "project_relevance_score", "evidence_strength"))
            lines.extend([f'<a id="{anchor}"></a>', "", f"### {markdown(paper['title'])}", "",
                          f"- 精读：{paper_link(paper, source, root)} · 本轮结论：{label}",
                          f"- 分数（技术贡献 / 直接相关性 / 证据）：{scores}",
                          f"- 任务：[{markdown(row.get('task_title', audit['task_title']))}](task_frontiers.md#task-{row['task_ids'][0]})",
                          f"- 判断：{markdown(row['reason'])}",
                          f"- 相对已有工作的增量：{markdown(audit.get('material_difference', '尚待核对'))}"])
            if audit.get("corrected_source_url"):
                lines.append(f"- 主源纠错线索（需继续核对）：[作者/原始入口]({audit['corrected_source_url']})")
            for evidence in audit.get("sources", []):
                lines.append(f"- 来源核查：[{markdown(evidence['locator'])}]({evidence['source_url']}) — {markdown(evidence['claim'])}（{evidence['status']}）")
            lines.extend([f"- 复查触发：{markdown(row['revisit_trigger'])}",
                          f"- [完整复审记录]({relative_link(source, root / artifact)})", ""])
        if decision != "priority":
            lines.extend(["</details>", ""])
    if later:
        lines.extend(["## 此次复审后按新版标准收录", "", "以下条目使用各自的新增验收记录，不改写先前存量复审。是否优先阅读仍以当前任务角色为准。", ""])
        for paper in later:
            anchor = "paper-" + hashlib.sha256(paper["url"].encode()).hexdigest()[:12]
            lines.extend([f'<a id="{anchor}"></a>', "", f"- {paper_link(paper, source, root)} · 见该论文精读和对应新增 run。", ""])
    return "\n".join(lines).rstrip() + "\n"


def build_indexes(registry: dict, frontiers: dict, root: Path) -> dict[Path, str]:
    """Validate all sources before producing any output or changing files."""
    errors = validate_task_frontiers(frontiers, registry, root=root)
    review_path = root / "data/library_review.seed.json"
    review = json.loads(review_path.read_text()) if review_path.is_file() else None
    if review is not None:
        errors += validate_library_review(review, registry, frontiers, root)
    elif any(p.get("curation_status") for b in registry.get("branches", []) for p in b.get("papers", [])):
        errors.append("curated records require data/library_review.seed.json")
    branches = registry.get("branches", [])
    if {branch.get("id") for branch in branches} != set(BRANCH_DIRECTORIES) or len(branches) != 5:
        errors.append("reading indexes require exactly the five registry branches A-E")
    for branch in branches:
        for paper in branch.get("papers", []):
            path = paper.get("deep_dive_path")
            if not isinstance(path, str) or not path.startswith("paper_reads/") or ".." in Path(path).parts:
                errors.append(f"paper {paper.get('title')} needs a safe deep_dive_path under paper_reads/")
            elif not (root / path).is_file():
                errors.append(f"paper {paper.get('title')} deep dive does not exist: {path}")
    if errors:
        raise ValueError("Reading index validation failed:\n" + "\n".join(f"- {error}" for error in errors))
    papers = {paper["url"]: paper for branch in branches for paper in branch["papers"]}
    memberships: dict[str, list[tuple[dict, dict]]] = {}
    for task in sorted(frontiers["tasks"], key=lambda task: task["task_id"]):
        for member in task["members"]:
            memberships.setdefault(member["paper_url"], []).append((task, member))

    def paper_line(paper: dict, source: Path) -> str:
        labels = [
            f"[{markdown(task['title'])}：{ROLE_LABELS[member['role']]}]"
            + f"({relative_link(source, root / 'paper_reads/task_frontiers.md')}#{paper_anchor(task['task_id'], paper['url'])})"
            for task, member in memberships.get(paper["url"], [])
        ]
        status = reading_status(paper, [m["role"] for _, m in memberships.get(paper["url"], [])])
        prefix = f"{DECISION_LABELS[status]} · " if status in DECISION_LABELS else ""
        return f"- {paper_link(paper, source, root)} · " + prefix + ("；".join(labels) if labels else "任务更迭：未审查")

    main_path = root / "paper_reads/README.md"
    main = [
        "# Paper Reads",
        "",
        GENERATED,
        "",
        f"Maintained deep dives: {len(papers)}",
        "",
        "[任务级当前推荐与历史基线](task_frontiers.md)",
        "",
        "本索引保留全部精读。任务角色只对相应 task 生效；任务推荐尚待可比证据的条目不默认 current。",
        "",
    ]
    output: dict[Path, str] = {}
    if review is not None:
        counts = {key: sum(reading_status(paper, [m["role"] for _, m in memberships.get(ref, [])]) == key for ref, paper in papers.items()) for key in DECISION_LABELS}
        main.extend([f"本次优先阅读：{counts['priority']} 篇；其余参考、观察、待视觉复核和来源待修复条目默认折叠。", "",
                     "[逐篇复审、分数与来源](library_review.md)", ""])
    for branch in sorted(branches, key=lambda branch: branch["id"]):
        branch_path = root / "paper_reads" / BRANCH_DIRECTORIES[branch["id"]] / "README.md"
        heading = f"{branch['id']}. {markdown(branch['name'])}"
        main.extend([f"## {heading}", "", f"Maintained deep dives: {len(branch['papers'])}", ""])
        primary = [p for p in branch["papers"] if reading_status(p, [m["role"] for _, m in memberships.get(p["url"], [])]) == "priority"] if review is not None else branch["papers"]
        other = [p for p in branch["papers"] if p not in primary] if review is not None else []
        main.extend(paper_line(paper, main_path) for paper in primary)
        if other:
            main.extend(["", "<details>", f"<summary>参考与待补证记录（{len(other)} 篇）</summary>", ""])
            main.extend(paper_line(paper, main_path) for paper in other)
            main.extend(["", "</details>"])
        main.append("")
        contents = [
            f"# {markdown(branch['name'])}",
            "",
            GENERATED,
            "",
            f"Maintained deep dives: {len(branch['papers'])}",
            "",
            "[完整精读库](../README.md) · [任务级推荐与历史基线](../task_frontiers.md)",
            "",
            "任务归档不删除精读，也不改变该论文在其他任务中的角色。未审查条目仍列在本分支全量索引中。",
            "",
        ]
        if review is not None:
            contents.extend([f"本轮优先阅读：{len(primary)} 篇。其余保留记录见折叠区；[逐篇复审](../library_review.md)。", ""])
        contents.extend(paper_line(paper, branch_path) for paper in primary)
        if other:
            contents.extend(["", "<details>", f"<summary>参考与待补证记录（{len(other)} 篇）</summary>", ""])
            contents.extend(paper_line(paper, branch_path) for paper in other)
            contents.extend(["", "</details>"])
        output[branch_path] = "\n".join(contents).rstrip() + "\n"
    output[main_path] = "\n".join(main).rstrip() + "\n"
    output[root / "paper_reads/task_frontiers.md"] = task_page(registry, frontiers, papers, root, review)
    if review is not None:
        output[root / "paper_reads/library_review.md"] = library_review_page(registry, review, root)
    return output


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--check", action="store_true", help="Fail if any generated index is missing or stale; write nothing.")
    args = parser.parse_args(argv)
    root = args.root.resolve()
    try:
        registry = json.loads((root / "data/papers.seed.json").read_text())
        frontiers = json.loads((root / "data/task_frontiers.seed.json").read_text())
        indexes = build_indexes(registry, frontiers, root)
    except (OSError, ValueError, KeyError, TypeError) as exc:
        print(str(exc), file=sys.stderr)
        return 1
    stale = [path for path, text in indexes.items() if not path.is_file() or path.read_text() != text]
    if args.check:
        if stale:
            print("Reading indexes are missing or stale:", file=sys.stderr)
            for path in stale:
                print(f"- {path.relative_to(root).as_posix()}", file=sys.stderr)
            return 1
        print(f"Reading indexes are current: {len(indexes)} files.")
        return 0
    for path in stale:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(indexes[path])
    print(f"Rendered reading indexes: {len(indexes)} files ({len(stale)} changed).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
